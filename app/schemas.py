"""
AutoWise AI - Pydantic Request & Response Schemas
"""

from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator


class VehicleInput(BaseModel):
    make: str = Field(
        ...,
        description="Vehicle manufacturer/brand (e.g., Toyota, Ford, BMW, Honda)",
        json_schema_extra={"example": "Toyota"}
    )
    year: int = Field(
        ...,
        ge=1950,
        le=2026,
        description="Model year of manufacture (1950 - 2026)",
        json_schema_extra={"example": 2018}
    )
    odometer: float = Field(
        ...,
        ge=0.0,
        le=2000000.0,
        description="Total mileage driven in miles (0 to 2,000,000)",
        json_schema_extra={"example": 45000.0}
    )
    condition: Optional[str] = Field(
        default="good",
        description="Physical and mechanical condition: excellent, good, like new, fair, salvage",
        json_schema_extra={"example": "good"}
    )
    cylinders: Optional[str] = Field(
        default="4 cylinders",
        description="Engine cylinders configuration (e.g. 4 cylinders, 6 cylinders, 8 cylinders, other)",
        json_schema_extra={"example": "4 cylinders"}
    )
    drive: Optional[str] = Field(
        default="fwd",
        description="Drivetrain type: fwd (front-wheel drive), rwd (rear-wheel drive), 4wd (all/four-wheel drive)",
        json_schema_extra={"example": "fwd"}
    )
    fuel: Optional[str] = Field(
        default="gas",
        description="Fuel type: gas, hybrid, diesel, electric, other",
        json_schema_extra={"example": "gas"}
    )
    transmission: Optional[str] = Field(
        default="automatic",
        description="Transmission type: automatic, manual, other",
        json_schema_extra={"example": "automatic"}
    )
    type: Optional[str] = Field(
        default="sedan",
        description="Vehicle body type: SUV, sedan, pickup, truck, coupe, hatchback, convertible, van, etc.",
        json_schema_extra={"example": "sedan"}
    )
    title_status: Optional[str] = Field(
        default="clean",
        description="Vehicle title status: clean, salvage, rebuilt, missing, parts only, lien",
        json_schema_extra={"example": "clean"}
    )
    paint_color: Optional[str] = Field(
        default="black",
        description="Exterior paint color: white, black, silver, grey, blue, red, etc.",
        json_schema_extra={"example": "black"}
    )

    @field_validator("make", "condition", "cylinders", "drive", "fuel", "transmission", "type", "title_status", "paint_color", mode="before")
    @classmethod
    def normalize_strings(cls, v):
        if isinstance(v, str):
            clean = v.strip().lower()
            return clean if clean else "missing"
        return v


class ContributingFactor(BaseModel):
    feature: str
    display_name: str
    value: Any
    relative_importance_pct: float
    impact_direction: str  # "increases_value", "decreases_value", "neutral"
    insight: str


class PredictionResponse(BaseModel):
    predicted_price: float = Field(..., description="Estimated vehicle resale price in USD ($)")
    formatted_price: str = Field(..., description="Currency-formatted price string (e.g. $18,450)")
    currency: str = Field(default="USD ($)")
    model_version: str = Field(default="1.0.0")
    algorithm: str = Field(default="DecisionTreeRegressor (depth regularized)")
    vehicle_summary: Dict[str, Any]
    top_contributing_factors: List[ContributingFactor]
    disclaimer: str = Field(
        default="This valuation is an automated statistical estimate generated by a machine learning model based on historical Kaggle dataset transactions. It does not replace a physical inspection or official appraisal."
    )


class ExplanationRequest(BaseModel):
    vehicle: VehicleInput
    predicted_price: float = Field(..., description="Predicted price output from /predict")
    user_question: Optional[str] = Field(
        default=None,
        description="Optional follow-up question from the user regarding this valuation"
    )


class ExplanationResponse(BaseModel):
    predicted_price: float
    formatted_price: str
    explanation_source: str = Field(
        ...,
        description="Source of the explanation: 'rule_based_engine', 'llm_gemini', or 'llm_openai'"
    )
    summary: str
    key_factors: List[str]
    valuation_context: str
    practical_checks: List[str]
    disclaimer: str


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    artifacts_available: bool
    llm_configured: bool
    llm_provider: str
    app_version: str


class ModelInfoResponse(BaseModel):
    model_version: str
    algorithm: str
    dataset: str
    target_column: str
    currency: str
    numeric_features: List[str]
    categorical_features: List[str]
    all_supported_features: List[str]
    feature_value_domains: Dict[str, List[str]]
    evaluation_metrics: Dict[str, Any]
    feature_importances: Dict[str, float]
    overfitting_analysis: Dict[str, Any]
    license_notice: str
